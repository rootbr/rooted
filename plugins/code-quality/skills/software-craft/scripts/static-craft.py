def language_of(path):
    name = os.path.basename(path)
    if name in BUILD_NAMES:
        return LANGUAGES.get(os.path.splitext(name)[1].lower(), "build")
    return LANGUAGES.get(os.path.splitext(name)[1].lower())


def kind_of(path, language):
    name = os.path.basename(path)
    if name in BUILD_NAMES or language == "build":
        return "build"
    if TEST_PATH.search(path):
        return "test"
    if language in CONFIG_LANGUAGES:
        return "config"
    if language in DOC_LANGUAGES:
        return "docs"
    return "source"


def deny_reason(path, head_text):
    """The deny-list: the reason a file is skipped, or None."""
    name = os.path.basename(path)
    if any(seg in ("/" + path) for seg in ("/" + v for v in VENDORED_DIRS)):
        return "vendored"
    if name in LOCK_FILES:
        return "lock"
    if GENERATED_NAME.search(name):
        return "generated"
    if head_text is not None:
        head_lines = head_text.split("\n")
        if any(GENERATED_MARK.search(l) for l in head_lines[:5]):
            return "generated"
        long_lines = [l for l in head_lines if l.strip()]
        if long_lines and sum(len(l) for l in long_lines) / len(long_lines) > MINIFIED_AVG_LINE:
            return "minified"
    if language_of(path) is None:
        return "unknown-language"
    return None


