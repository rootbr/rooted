package inventory

import (
	"net/url"

	"example.com/inventory/supplierpb"
)

// SupplierClient talks to a supplier's purchase-order API on behalf of one tenant.
type SupplierClient struct {
	publicBaseURL string
	tenant        string
}

// Webhook is a subscription the supplier calls back on when a purchase order changes.
type Webhook struct {
	Event       string
	CallbackURL string
	Secret      string
}

// WebhookTarget returns the address on this service that the supplier posts events of one kind to.
func (c *SupplierClient) WebhookTarget(eventKind string) string {
	callbackUrl := c.publicBaseURL + "/hooks/" + url.PathEscape(eventKind)
	if c.tenant != "" {
		callbackUrl += "?tenant=" + url.QueryEscape(c.tenant)
	}
	return callbackUrl
}

// webhookFromProto converts the supplier API's webhook message into a Webhook.
func webhookFromProto(message *supplierpb.Webhook) Webhook {
	// The getters are generated by protoc-gen-go from the message's snake_case fields.
	return Webhook{
		Event:       message.GetEventKind(),
		CallbackURL: message.GetCallbackUrl(),
		Secret:      message.GetSigningSecret(),
	}
}
